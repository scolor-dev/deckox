const RECOVERY_CODE_COUNT: usize = 10;

/// Key of the single administrator account in [`AccountFile`]. The file is
/// already keyed by username so Deckox can grow multiple accounts later
/// without another migration; today only this one key is ever populated.
pub const ADMIN_ACCOUNT: &str = "admin";

/// On-disk shape of the admin account file (JSON). Written atomically and
/// read back on every [`AuthManager::load`] and every CLI recovery command.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct AccountFile {
    pub accounts: HashMap<String, Account>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Account {
    pub password_hash: String,
    #[serde(default)]
    pub totp: Option<TotpSecret>,
    #[serde(default)]
    pub updated_at_ms: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TotpSecret {
    pub secret_base32: String,
    pub recovery_code_hashes: Vec<String>,
    /// The TOTP time-step last accepted for this account, if any. Codes
    /// matching this step or an older one are rejected so a captured code
    /// cannot be replayed for the rest of its ~90s (skew ±1) validity window.
    #[serde(default)]
    pub last_used_step: Option<u64>,
}

#[derive(Clone)]
pub struct AuthManager {
    inner: Arc<AuthInner>,
}

struct AuthInner {
    account: RwLock<Account>,
    account_path: Option<PathBuf>,
    secure_cookie: bool,
    sessions: Mutex<HashMap<String, Instant>>,
    failures: Mutex<HashMap<IpAddr, FailedLogins>>,
    password_change_failures: Mutex<HashMap<IpAddr, FailedLogins>>,
    totp_login_failures: Mutex<HashMap<IpAddr, FailedLogins>>,
    account_write: Mutex<()>,
    audit: AuditLog,
    /// Password verified, TOTP not yet: keyed by a short-lived pre-auth
    /// token handed to the browser instead of the real session cookie.
    pending_logins: Mutex<HashMap<String, Instant>>,
    /// A TOTP secret generated by `totp/setup` but not yet confirmed with a
    /// code, keyed by the session token of the admin who requested it.
    pending_totp_setup: Mutex<HashMap<String, PendingTotpSetup>>,
}

struct FailedLogins {
    count: u32,
    started_at: Instant,
}

#[derive(Clone)]
struct PendingTotpSetup {
    secret_base32: String,
    expires_at: Instant,
}

