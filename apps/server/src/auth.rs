impl AuthManager {
    pub fn load(audit: AuditLog) -> Result<Self, String> {
        let (account, account_path) = if let Ok(password_hash) =
            env::var("DECKOX_ADMIN_PASSWORD_HASH")
        {
            let password_hash = password_hash.trim().to_owned();
            PasswordHash::new(&password_hash)
                .map_err(|error| format!("invalid admin password hash: {error}"))?;
            (
                Account {
                    password_hash,
                    totp: None,
                    updated_at_ms: 0,
                },
                None,
            )
        } else {
            let path = PathBuf::from(
                env::var("DECKOX_ADMIN_PASSWORD_HASH_FILE")
                    .unwrap_or_else(|_| DEFAULT_PASSWORD_HASH_FILE.to_owned()),
            );
            let account_file = load_account_file(&path)
                .map_err(|error| format!("failed to read {}: {error}", path.display()))?;
            let account = account_file
                .accounts
                .get(ADMIN_ACCOUNT)
                .cloned()
                .ok_or_else(|| format!("{} does not contain an admin account", path.display()))?;
            (account, Some(path))
        };

        let secure_cookie = env::var("DECKOX_SECURE_COOKIE").is_ok_and(|value| value == "true");
        Ok(Self {
            inner: Arc::new(AuthInner {
                account: RwLock::new(account),
                account_path,
                secure_cookie,
                sessions: Mutex::new(HashMap::new()),
                failures: Mutex::new(HashMap::new()),
                password_change_failures: Mutex::new(HashMap::new()),
                totp_login_failures: Mutex::new(HashMap::new()),
                account_write: Mutex::new(()),
                audit,
                pending_logins: Mutex::new(HashMap::new()),
                pending_totp_setup: Mutex::new(HashMap::new()),
            }),
        })
    }

    async fn login(&self, source_ip: IpAddr, password: String) -> LoginResult {
        if password.is_empty() || password.len() > MAX_PASSWORD_BYTES {
            record_failure(&self.inner.failures, source_ip).await;
            return LoginResult::Invalid;
        }
        if is_rate_limited(&self.inner.failures, source_ip).await {
            return LoginResult::RateLimited;
        }

        let account = self.inner.account.read().await.clone();
        let valid = verify_password(account.password_hash.clone(), password).await;

        if !valid {
            record_failure(&self.inner.failures, source_ip).await;
            return LoginResult::Invalid;
        }

        self.inner.failures.lock().await.remove(&source_ip);
        self.inner
            .password_change_failures
            .lock()
            .await
            .remove(&source_ip);

        if account.totp.is_some() {
            let preauth_token = hex::encode(rand::random::<[u8; 32]>());
            let now = Instant::now();
            let mut pending = self.inner.pending_logins.lock().await;
            pending.retain(|_, expires_at| *expires_at > now);
            pending.insert(preauth_token.clone(), now + PREAUTH_TTL);
            drop(pending);
            return LoginResult::TotpRequired(preauth_token);
        }

        let token = hex::encode(rand::random::<[u8; 32]>());
        self.inner
            .sessions
            .lock()
            .await
            .insert(token.clone(), Instant::now() + SESSION_TTL);
        LoginResult::Authenticated(token)
    }

    async fn login_totp(
        &self,
        source_ip: IpAddr,
        headers: &HeaderMap,
        code: String,
    ) -> LoginTotpResult {
        let Some(preauth_token) = preauth_token(headers) else {
            return LoginTotpResult::NoPendingLogin;
        };
        if is_rate_limited(&self.inner.totp_login_failures, source_ip).await {
            return LoginTotpResult::RateLimited;
        }

        let now = Instant::now();
        let mut pending = self.inner.pending_logins.lock().await;
        pending.retain(|_, expires_at| *expires_at > now);
        let is_pending = pending.remove(&preauth_token).is_some();
        drop(pending);
        if !is_pending {
            return LoginTotpResult::NoPendingLogin;
        }

        let mut account = self.inner.account.read().await.clone();
        let valid = verify_totp_or_recovery_code(&mut account, &code).await;
        if !valid {
            record_failure(&self.inner.totp_login_failures, source_ip).await;
            return LoginTotpResult::Invalid;
        }
        if let Some(account_path) = self.inner.account_path.clone() {
            // Best-effort: the submitted code was valid either way. If this
            // write fails, the consumed recovery code reverts to available
            // on the next process restart rather than blocking the login.
            if let Err(error) = write_account(&account_path, &account).await {
                warn!(%error, "failed to persist recovery code consumption");
            }
        }
        *self.inner.account.write().await = account;

        self.inner
            .totp_login_failures
            .lock()
            .await
            .remove(&source_ip);
        let token = hex::encode(rand::random::<[u8; 32]>());
        self.inner
            .sessions
            .lock()
            .await
            .insert(token.clone(), Instant::now() + SESSION_TTL);
        LoginTotpResult::Authenticated(token)
    }

    async fn change_password(
        &self,
        source_ip: IpAddr,
        current_password: String,
        new_password: String,
    ) -> ChangePasswordResult {
        let _change_guard = self.inner.account_write.lock().await;
        let Some(account_path) = self.inner.account_path.clone() else {
            return ChangePasswordResult::NotPersistent;
        };
        if validate_new_password(&new_password).is_err() {
            return ChangePasswordResult::InvalidNewPassword;
        }
        if is_rate_limited(&self.inner.password_change_failures, source_ip).await {
            return ChangePasswordResult::RateLimited;
        }

        let current_hash = self.inner.account.read().await.password_hash.clone();
        if !verify_password(current_hash, current_password).await {
            record_failure(&self.inner.password_change_failures, source_ip).await;
            return ChangePasswordResult::InvalidCurrentPassword;
        }
        self.inner
            .password_change_failures
            .lock()
            .await
            .remove(&source_ip);

        let password_to_hash = new_password;
        let new_hash =
            match tokio::task::spawn_blocking(move || hash_password(&password_to_hash)).await {
                Ok(Ok(hash)) => hash,
                Ok(Err(error)) => return ChangePasswordResult::Failed(error),
                Err(error) => {
                    return ChangePasswordResult::Failed(format!(
                        "password hashing task failed: {error}"
                    ));
                }
            };

        let mut account = self.inner.account.read().await.clone();
        account.password_hash = new_hash;
        account.updated_at_ms = now_ms();
        if let Err(error) = write_account(&account_path, &account).await {
            return ChangePasswordResult::Failed(error);
        }
        *self.inner.account.write().await = account;

        self.inner.sessions.lock().await.clear();
        self.inner.failures.lock().await.clear();
        ChangePasswordResult::Changed
    }

    pub async fn confirm_current_password(
        &self,
        source_ip: IpAddr,
        password: String,
    ) -> PasswordConfirmationResult {
        if password.is_empty() || password.len() > MAX_PASSWORD_BYTES {
            record_failure(&self.inner.password_change_failures, source_ip).await;
            return PasswordConfirmationResult::Invalid;
        }
        if is_rate_limited(&self.inner.password_change_failures, source_ip).await {
            return PasswordConfirmationResult::RateLimited;
        }

        let password_hash = self.inner.account.read().await.password_hash.clone();
        if !verify_password(password_hash, password).await {
            record_failure(&self.inner.password_change_failures, source_ip).await;
            return PasswordConfirmationResult::Invalid;
        }
        self.inner
            .password_change_failures
            .lock()
            .await
            .remove(&source_ip);
        PasswordConfirmationResult::Confirmed
    }

    async fn is_authenticated(&self, headers: &HeaderMap) -> bool {
        let Some(token) = session_token(headers) else {
            return false;
        };
        let now = Instant::now();
        let mut sessions = self.inner.sessions.lock().await;
        sessions.retain(|_, expires_at| *expires_at > now);
        sessions
            .get(&token)
            .is_some_and(|expires_at| *expires_at > now)
    }

    async fn logout(&self, headers: &HeaderMap) {
        if let Some(token) = session_token(headers) {
            self.inner.sessions.lock().await.remove(&token);
        }
    }

    async fn totp_status(&self) -> TotpStatusResponse {
        self.inner.account.read().await.totp.as_ref().map_or(
            TotpStatusResponse {
                enabled: false,
                recovery_codes_remaining: 0,
            },
            |totp| TotpStatusResponse {
                enabled: true,
                recovery_codes_remaining: totp.recovery_code_hashes.len(),
            },
        )
    }

    async fn totp_setup(&self, session_token: &str) -> TotpSetupResult {
        if self.inner.account_path.is_none() {
            return TotpSetupResult::NotPersistent;
        }
        let totp = match generate_totp_secret() {
            Ok(totp) => totp,
            Err(error) => return TotpSetupResult::Failed(error),
        };
        let secret_base32 = totp.get_secret_base32();
        let otpauth_uri = totp.get_url();

        let now = Instant::now();
        let mut pending = self.inner.pending_totp_setup.lock().await;
        pending.retain(|_, entry| entry.expires_at > now);
        pending.insert(
            session_token.to_owned(),
            PendingTotpSetup {
                secret_base32: secret_base32.clone(),
                expires_at: now + PENDING_TOTP_SETUP_TTL,
            },
        );
        drop(pending);
        TotpSetupResult::Ready {
            secret_base32,
            otpauth_uri,
        }
    }

    async fn totp_confirm(&self, session_token: &str, code: String) -> TotpConfirmResult {
        let Some(account_path) = self.inner.account_path.clone() else {
            return TotpConfirmResult::NotPersistent;
        };

        let now = Instant::now();
        let mut pending = self.inner.pending_totp_setup.lock().await;
        pending.retain(|_, entry| entry.expires_at > now);
        let Some(entry) = pending.get(session_token).cloned() else {
            return TotpConfirmResult::NoPendingSetup;
        };
        drop(pending);

        let totp = match build_totp(&entry.secret_base32) {
            Ok(totp) => totp,
            Err(error) => return TotpConfirmResult::Failed(error),
        };
        let Some(step) = totp_matching_step(&totp, &code, None) else {
            return TotpConfirmResult::InvalidCode;
        };

        let recovery_codes = generate_recovery_codes();
        let recovery_code_hashes = match hash_recovery_codes(&recovery_codes).await {
            Ok(hashes) => hashes,
            Err(error) => return TotpConfirmResult::Failed(error),
        };

        let mut account = self.inner.account.read().await.clone();
        account.totp = Some(TotpSecret {
            secret_base32: entry.secret_base32,
            recovery_code_hashes,
            last_used_step: Some(step),
        });
        account.updated_at_ms = now_ms();
        if let Err(error) = write_account(&account_path, &account).await {
            return TotpConfirmResult::Failed(error);
        }
        *self.inner.account.write().await = account;
        self.inner
            .pending_totp_setup
            .lock()
            .await
            .remove(session_token);

        TotpConfirmResult::Confirmed(recovery_codes)
    }

    async fn totp_disable(
        &self,
        source_ip: IpAddr,
        current_password: String,
        code: String,
    ) -> TotpDisableResult {
        let Some(account_path) = self.inner.account_path.clone() else {
            return TotpDisableResult::NotPersistent;
        };
        if is_rate_limited(&self.inner.password_change_failures, source_ip).await {
            return TotpDisableResult::RateLimited;
        }

        let mut account = self.inner.account.read().await.clone();
        if !verify_password(account.password_hash.clone(), current_password).await {
            record_failure(&self.inner.password_change_failures, source_ip).await;
            return TotpDisableResult::InvalidCurrentPassword;
        }
        if account.totp.is_none() {
            return TotpDisableResult::NotEnabled;
        }
        if !verify_totp_or_recovery_code(&mut account, &code).await {
            record_failure(&self.inner.password_change_failures, source_ip).await;
            return TotpDisableResult::InvalidCode;
        }
        self.inner
            .password_change_failures
            .lock()
            .await
            .remove(&source_ip);

        account.totp = None;
        account.updated_at_ms = now_ms();
        if let Err(error) = write_account(&account_path, &account).await {
            return TotpDisableResult::Failed(error);
        }
        *self.inner.account.write().await = account;
        TotpDisableResult::Disabled
    }

    fn session_cookie(&self, token: &str) -> String {
        self.cookie(SESSION_COOKIE, token, SESSION_TTL.as_secs())
    }

    fn expired_cookie(&self) -> String {
        self.expired(SESSION_COOKIE)
    }

    fn preauth_cookie(&self, token: &str) -> String {
        self.cookie(PREAUTH_COOKIE, token, PREAUTH_TTL.as_secs())
    }

    fn expired_preauth_cookie(&self) -> String {
        self.expired(PREAUTH_COOKIE)
    }

    fn cookie(&self, name: &str, token: &str, max_age_secs: u64) -> String {
        let secure = if self.inner.secure_cookie {
            "; Secure"
        } else {
            ""
        };
        format!("{name}={token}; Path=/; HttpOnly; SameSite=Strict; Max-Age={max_age_secs}{secure}")
    }

    fn expired(&self, name: &str) -> String {
        let secure = if self.inner.secure_cookie {
            "; Secure"
        } else {
            ""
        };
        format!("{name}=; Path=/; HttpOnly; SameSite=Strict; Max-Age=0{secure}")
    }

    pub fn audit(&self) -> &AuditLog {
        &self.inner.audit
    }
}

/// Builds a [`TOTP`] from a newly generated random secret, for the setup
/// step. `account_name` is fixed to [`ADMIN_ACCOUNT`] since Deckox has one
/// administrator today.
fn generate_totp_secret() -> Result<TOTP, String> {
    let secret_bytes = Secret::generate_secret()
        .to_bytes()
        .map_err(|error| format!("failed to generate TOTP secret: {error}"))?;
    build_totp_from_bytes(secret_bytes)
}

/// Rebuilds the [`TOTP`] used to verify codes against a previously stored,
/// base32-encoded secret.
fn build_totp(secret_base32: &str) -> Result<TOTP, String> {
    let secret_bytes = Secret::Encoded(secret_base32.to_owned())
        .to_bytes()
        .map_err(|error| format!("invalid TOTP secret: {error}"))?;
    build_totp_from_bytes(secret_bytes)
}

fn build_totp_from_bytes(secret_bytes: Vec<u8>) -> Result<TOTP, String> {
    TOTP::new(
        Algorithm::SHA1,
        TOTP_DIGITS,
        TOTP_SKEW,
        TOTP_STEP,
        secret_bytes,
        Some(TOTP_ISSUER.to_owned()),
        ADMIN_ACCOUNT.to_owned(),
    )
    .map_err(|error| format!("invalid TOTP configuration: {error}"))
}

/// Generates human-typeable one-time recovery codes (`XXXXX-XXXXX`, 40 bits
/// of entropy each). Callers hash these with [`hash_recovery_codes`] before
/// persisting — only the plaintext response to the confirming client ever
/// sees them.
fn generate_recovery_codes() -> Vec<String> {
    (0..RECOVERY_CODE_COUNT)
        .map(|_| {
            let raw = hex::encode(rand::random::<[u8; 5]>()).to_uppercase();
            format!("{}-{}", &raw[..5], &raw[5..])
        })
        .collect()
}

async fn hash_recovery_codes(codes: &[String]) -> Result<Vec<String>, String> {
    let codes = codes.to_vec();
    tokio::task::spawn_blocking(move || {
        codes
            .iter()
            .map(|code| hash_password(code))
            .collect::<Result<Vec<_>, _>>()
    })
    .await
    .map_err(|error| format!("recovery code hashing task failed: {error}"))?
}

/// Checks `code` against the account's TOTP secret first, then falls back to
/// the stored recovery codes. A matching recovery code is removed from
/// `account` (one-time use) — the caller is responsible for persisting that
/// change.
async fn verify_totp_or_recovery_code(account: &mut Account, code: &str) -> bool {
    let Some(totp_secret) = account.totp.clone() else {
        return false;
    };
    if let Ok(totp) = build_totp(&totp_secret.secret_base32)
        && let Some(step) = totp_matching_step(&totp, code, totp_secret.last_used_step)
    {
        if let Some(totp_mut) = account.totp.as_mut() {
            totp_mut.last_used_step = Some(step);
        }
        return true;
    }

    let Some(totp) = account.totp.as_mut() else {
        return false;
    };
    for index in 0..totp.recovery_code_hashes.len() {
        if verify_password(totp.recovery_code_hashes[index].clone(), code.to_owned()).await {
            totp.recovery_code_hashes.remove(index);
            return true;
        }
    }
    false
}

/// Returns the TOTP time-step `code` matches, if any, restricted to steps
/// strictly newer than `after_step`. Mirrors [`TOTP::check`]'s skew window
/// but additionally rejects a code already accepted for an equal-or-older
/// step, so a captured code cannot be replayed within its validity window.
fn totp_matching_step(totp: &TOTP, code: &str, after_step: Option<u64>) -> Option<u64> {
    let now_secs = now_ms() / 1000;
    let base_step = now_secs / TOTP_STEP;
    let skew = u64::from(TOTP_SKEW);
    (base_step.saturating_sub(skew)..=base_step + skew).find(|&step| {
        after_step.is_none_or(|after| step > after) && totp.generate(step * TOTP_STEP) == code
    })
}

/// Resolves the account file path a CLI recovery command should operate on.
/// Returns `None` when the server is configured for the non-persistent
/// `DECKOX_ADMIN_PASSWORD_HASH` mode, in which there is no file to edit.
pub fn account_path_from_env() -> Option<PathBuf> {
    if env::var("DECKOX_ADMIN_PASSWORD_HASH").is_ok() {
        return None;
    }
    Some(PathBuf::from(
        env::var("DECKOX_ADMIN_PASSWORD_HASH_FILE")
            .unwrap_or_else(|_| DEFAULT_PASSWORD_HASH_FILE.to_owned()),
    ))
}

/// Parses an account file, transparently upgrading the legacy format (a bare
/// Argon2id hash string, with no JSON structure) that every Deckox install
/// before this feature wrote. The upgraded form is only persisted the next
/// time the account is written (password change, TOTP enable/disable, or a
/// CLI recovery command) — reading never touches the file on disk.
pub fn load_account_file(path: &Path) -> Result<AccountFile, String> {
    let content = fs::read_to_string(path)
        .map_err(|error| format!("failed to read {}: {error}", path.display()))?;
    let trimmed = content.trim();

    if let Ok(parsed) = serde_json::from_str::<AccountFile>(trimmed) {
        return Ok(parsed);
    }

    PasswordHash::new(trimmed).map_err(|error| format!("invalid admin password hash: {error}"))?;
    let mut accounts = HashMap::new();
    accounts.insert(
        ADMIN_ACCOUNT.to_owned(),
        Account {
            password_hash: trimmed.to_owned(),
            totp: None,
            updated_at_ms: 0,
        },
    );
    Ok(AccountFile { accounts })
}

/// Writes the admin account back to `path` in the current JSON format.
/// Shared by the running server (password change, TOTP changes) and the
/// `reset-password` / `disable-totp` CLI subcommands, which call it directly
/// without going through [`AuthManager`].
pub async fn write_account(path: &Path, account: &Account) -> Result<(), String> {
    let mut accounts = HashMap::new();
    accounts.insert(ADMIN_ACCOUNT.to_owned(), account.clone());
    let file = AccountFile { accounts };
    let serialized = serde_json::to_vec_pretty(&file)
        .map_err(|error| format!("failed to encode account file: {error}"))?;
    atomic_write_secure(path, &serialized).await
}

pub fn now_ms() -> u64 {
    use std::time::{SystemTime, UNIX_EPOCH};
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |duration| {
            u64::try_from(duration.as_millis()).unwrap_or(u64::MAX)
        })
}

async fn is_rate_limited(
    failures: &Mutex<HashMap<IpAddr, FailedLogins>>,
    source_ip: IpAddr,
) -> bool {
    let now = Instant::now();
    let mut failures = failures.lock().await;
    failures.retain(|_, entry| now.duration_since(entry.started_at) < FAILURE_WINDOW);
    failures
        .get(&source_ip)
        .is_some_and(|entry| entry.count >= MAX_FAILURES)
}

async fn record_failure(failures: &Mutex<HashMap<IpAddr, FailedLogins>>, source_ip: IpAddr) {
    let now = Instant::now();
    let mut failures = failures.lock().await;
    let entry = failures.entry(source_ip).or_insert(FailedLogins {
        count: 0,
        started_at: now,
    });
    if now.duration_since(entry.started_at) >= FAILURE_WINDOW {
        entry.count = 0;
        entry.started_at = now;
    }
    entry.count = entry.count.saturating_add(1);
    drop(failures);
}

async fn verify_password(password_hash: String, password: String) -> bool {
    tokio::task::spawn_blocking(move || {
        let Ok(parsed_hash) = PasswordHash::new(&password_hash) else {
            return false;
        };
        Argon2::default()
            .verify_password(password.as_bytes(), &parsed_hash)
            .is_ok()
    })
    .await
    .unwrap_or(false)
}

pub fn hash_password(password: &str) -> Result<String, String> {
    if password.is_empty() || password.len() > MAX_PASSWORD_BYTES {
        return Err("password must contain between 1 and 1024 bytes".to_owned());
    }
    let salt = SaltString::encode_b64(&rand::random::<[u8; 16]>())
        .map_err(|error| format!("failed to create password salt: {error}"))?;
    Argon2::default()
        .hash_password(password.as_bytes(), &salt)
        .map(|hash| hash.to_string())
        .map_err(|error| format!("failed to hash password: {error}"))
}

/// Shared by the web password-change endpoint and the `reset-password` CLI
/// command so both enforce the same strength floor.
pub fn validate_new_password(password: &str) -> Result<(), String> {
    if password.len() < MIN_PASSWORD_BYTES || password.len() > MAX_PASSWORD_BYTES {
        return Err(format!(
            "password must contain between {MIN_PASSWORD_BYTES} and {MAX_PASSWORD_BYTES} bytes"
        ));
    }
    Ok(())
}

pub async fn login(
    State(auth): State<AuthManager>,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    axum::Extension(request_id): axum::Extension<RequestId>,
    headers: HeaderMap,
    Json(payload): Json<LoginRequest>,
) -> Response {
    if !same_origin(&headers) {
        warn!(
            event = "auth_login",
            request_id = %request_id.0,
            source_ip = %peer.ip(),
            result = "rejected",
            reason = "origin",
            "login rejected"
        );
        return error_response(
            StatusCode::FORBIDDEN,
            "forbidden",
            "request origin is not allowed",
        );
    }

    match auth.login(peer.ip(), payload.password).await {
        LoginResult::Authenticated(token) => {
            info!(
                event = "auth_login",
                request_id = %request_id.0,
                actor = "admin",
                source_ip = %peer.ip(),
                result = "success",
                "administrator logged in"
            );
            auth.audit()
                .record_admin("auth_login", peer.ip(), "success", None)
                .await;
            let mut response = Json(AuthStatus::authenticated()).into_response();
            if let Ok(value) = HeaderValue::from_str(&auth.session_cookie(&token)) {
                response.headers_mut().insert(SET_COOKIE, value);
            }
            response
        }
        LoginResult::TotpRequired(preauth_token) => {
            info!(
                event = "auth_login",
                request_id = %request_id.0,
                actor = "admin",
                source_ip = %peer.ip(),
                result = "totp_required",
                "administrator password confirmed; two-factor code required"
            );
            auth.audit()
                .record_admin("auth_login", peer.ip(), "totp_required", None)
                .await;
            let mut response = Json(AuthStatus::totp_required()).into_response();
            if let Ok(value) = HeaderValue::from_str(&auth.preauth_cookie(&preauth_token)) {
                response.headers_mut().insert(SET_COOKIE, value);
            }
            response
        }
        LoginResult::Invalid => {
            warn!(
                event = "auth_login",
                request_id = %request_id.0,
                source_ip = %peer.ip(),
                result = "failure",
                "administrator login failed"
            );
            auth.audit()
                .record_admin("auth_login", peer.ip(), "failure", None)
                .await;
            error_response(
                StatusCode::UNAUTHORIZED,
                "invalid_credentials",
                "password is incorrect",
            )
        }
        LoginResult::RateLimited => {
            warn!(
                event = "auth_login",
                request_id = %request_id.0,
                source_ip = %peer.ip(),
                result = "rate_limited",
                "administrator login rate limited"
            );
            auth.audit()
                .record_admin("auth_login", peer.ip(), "rate_limited", None)
                .await;
            error_response(
                StatusCode::TOO_MANY_REQUESTS,
                "rate_limited",
                "too many login attempts; try again later",
            )
        }
    }
}

