    #[tokio::test]
    async fn recovery_code_is_consumed_after_use() {
        let mut account = Account {
            password_hash: hash_password("pw-for-recovery-test").expect("password should hash"),
            totp: Some(super::TotpSecret {
                secret_base32: "JBSWY3DPEHPK3PXP".to_owned(),
                recovery_code_hashes: vec![
                    hash_password("ABCDE-12345").expect("recovery code should hash"),
                ],
                last_used_step: None,
            }),
            updated_at_ms: 0,
        };

        assert!(super::verify_totp_or_recovery_code(&mut account, "ABCDE-12345").await);
        assert!(
            account
                .totp
                .as_ref()
                .unwrap()
                .recovery_code_hashes
                .is_empty(),
            "a used recovery code must be removed"
        );
        assert!(
            !super::verify_totp_or_recovery_code(&mut account, "ABCDE-12345").await,
            "a consumed recovery code must not verify again"
        );
    }

    #[tokio::test]
    async fn totp_setup_confirm_and_login_round_trip() {
        let path = std::env::temp_dir().join(format!(
            "deckox-totp-test-{}.json",
            hex::encode(rand::random::<[u8; 8]>())
        ));
        let auth = test_auth_with_path("totp-round-trip-password", Some(path.clone()));
        let session_token = "test-session-token";

        let super::TotpSetupResult::Ready { secret_base32, .. } =
            auth.totp_setup(session_token).await
        else {
            panic!("setup should succeed for a persistent account");
        };
        let code = super::build_totp(&secret_base32)
            .expect("stored secret should build a TOTP")
            .generate_current()
            .expect("a code should generate for the current time");

        let super::TotpConfirmResult::Confirmed(recovery_codes) =
            auth.totp_confirm(session_token, code.clone()).await
        else {
            panic!("confirm should succeed with a valid code");
        };
        assert_eq!(recovery_codes.len(), super::RECOVERY_CODE_COUNT);

        let source_ip = IpAddr::from([192, 0, 2, 10]);
        let super::LoginResult::TotpRequired(preauth_token) = auth
            .login(source_ip, "totp-round-trip-password".to_owned())
            .await
        else {
            panic!("login should require a TOTP code once enabled");
        };

        let mut headers = HeaderMap::new();
        headers.insert(
            header::COOKIE,
            HeaderValue::from_str(&format!("deckox_preauth={preauth_token}"))
                .expect("cookie header should build"),
        );
        assert!(
            !matches!(
                auth.login_totp(source_ip, &headers, code).await,
                super::LoginTotpResult::Authenticated(_)
            ),
            "the code already accepted by confirm must not be replayable for login"
        );

        let super::LoginResult::TotpRequired(preauth_token) = auth
            .login(source_ip, "totp-round-trip-password".to_owned())
            .await
        else {
            panic!("login should still require a TOTP code after the failed replay");
        };
        headers.insert(
            header::COOKIE,
            HeaderValue::from_str(&format!("deckox_preauth={preauth_token}"))
                .expect("cookie header should build"),
        );
        assert!(
            matches!(
                auth.login_totp(source_ip, &headers, recovery_codes[0].clone())
                    .await,
                super::LoginTotpResult::Authenticated(_)
            ),
            "a fresh recovery code should still authenticate"
        );

        let _ = std::fs::remove_file(&path);
    }
