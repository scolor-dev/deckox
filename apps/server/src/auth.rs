pub async fn require_auth(
    State(auth): State<AuthManager>,
    mut request: Request,
    next: Next,
) -> Response {
    let source_ip = request
        .extensions()
        .get::<ConnectInfo<SocketAddr>>()
        .map_or_else(|| IpAddr::from([0, 0, 0, 0]), |peer| peer.ip());
    let request_id = request
        .extensions()
        .get::<RequestId>()
        .map_or("unknown", |value| value.0.as_str());

    if !auth.is_authenticated(request.headers()).await {
        warn!(
            event = "auth_required",
            request_id,
            source_ip = %source_ip,
            result = "rejected",
            "unauthenticated API request rejected"
        );
        return error_response(
            StatusCode::UNAUTHORIZED,
            "authentication_required",
            "authentication is required",
        );
    }
    if requires_same_origin(request.method(), request.headers()) && !same_origin(request.headers())
    {
        warn!(
            event = "auth_origin",
            request_id,
            actor = "admin",
            source_ip = %source_ip,
            result = "rejected",
            "cross-origin API request rejected"
        );
        return error_response(
            StatusCode::FORBIDDEN,
            "forbidden",
            "request origin is not allowed",
        );
    }

    request
        .extensions_mut()
        .insert(AuthenticatedUser { source_ip });
    next.run(request).await
}

fn session_token(headers: &HeaderMap) -> Option<String> {
    cookie_value(headers, SESSION_COOKIE)
}

fn preauth_token(headers: &HeaderMap) -> Option<String> {
    cookie_value(headers, PREAUTH_COOKIE)
}

fn cookie_value(headers: &HeaderMap, name: &str) -> Option<String> {
    headers
        .get(COOKIE)?
        .to_str()
        .ok()?
        .split(';')
        .find_map(|cookie| {
            let (cookie_name, value) = cookie.trim().split_once('=')?;
            (cookie_name == name && !value.is_empty()).then(|| value.to_owned())
        })
}

fn same_origin(headers: &HeaderMap) -> bool {
    let Some(host) = headers.get(HOST).and_then(|value| value.to_str().ok()) else {
        return false;
    };
    let Some(origin) = headers.get(ORIGIN).and_then(|value| value.to_str().ok()) else {
        return false;
    };
    origin == format!("http://{host}") || origin == format!("https://{host}")
}

const fn is_state_changing(method: &Method) -> bool {
    !matches!(*method, Method::GET | Method::HEAD | Method::OPTIONS)
}

fn requires_same_origin(method: &Method, headers: &HeaderMap) -> bool {
    is_state_changing(method)
        || headers
            .get(UPGRADE)
            .is_some_and(|value| value.as_bytes().eq_ignore_ascii_case(b"websocket"))
}

fn error_response(status: StatusCode, code: &'static str, message: &'static str) -> Response {
    (
        status,
        Json(ErrorResponse {
            code,
            message: message.to_owned(),
        }),
    )
        .into_response()
}

